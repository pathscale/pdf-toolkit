// gen-standard14.ts AFM_DIR OUT_RS
// Generates pdf-text/src/data/standard14.rs from Adobe's Core 14 AFM files (see NOTICE): for each
// font, the advance width (WX) of every glyph, keyed by Unicode through the glyph names in
// pdf-text/src/data/encodings.rs and sorted for binary search. Data only; run with bun.
const [dir, out] = process.argv.slice(2);
if (!dir || !out) {
  console.error("usage: bun gen-standard14.ts AFM_DIR OUT_RS");
  process.exit(1);
}
const encodings = await Bun.file(new URL("../pdf-text/src/data/encodings.rs", import.meta.url)).text();
const glyphs = new Map<string, number>();
for (const m of encodings.matchAll(/\("([^"]+)", 0x([0-9a-f]{4})\)/g)) glyphs.set(m[1], parseInt(m[2], 16));

// Latin Extended-A names: a base letter plus an accent suffix, composed with NFC. AGL maps the
// comma-accented g, k, l, n, r (and capitals) to the cedilla code points, so those use U+0327.
const marks: [string, string][] = [
  ["hungarumlaut", "̋"], ["commaaccent", "̦"], ["dotaccent", "̇"], ["cedilla", "̧"],
  ["ogonek", "̨"], ["macron", "̄"], ["acute", "́"], ["breve", "̆"], ["caron", "̌"],
  ["ring", "̊"],
];
const special: Record<string, number> = { Dcroat: 0x0110, dcroat: 0x0111 };

function unicodeFor(name: string): number | undefined {
  if (glyphs.has(name)) return glyphs.get(name);
  if (name in special) return special[name];
  const uni = /^uni([0-9A-F]{4})$/.exec(name);
  if (uni) return parseInt(uni[1], 16);
  for (const [suffix, mark] of marks) {
    if (name.length !== suffix.length + 1 || !name.endsWith(suffix)) continue;
    const base = name[0];
    const combining = suffix === "commaaccent" && "GgKkLlNnRr".includes(base) ? "̧" : mark;
    const composed = (base + combining).normalize("NFC");
    if ([...composed].length === 1) return composed.codePointAt(0);
  }
  return undefined;
}

const fonts = [
  ["COURIER", "Courier"], ["COURIER_BOLD", "Courier-Bold"], ["COURIER_OBLIQUE", "Courier-Oblique"],
  ["COURIER_BOLD_OBLIQUE", "Courier-BoldOblique"], ["HELVETICA", "Helvetica"], ["HELVETICA_BOLD", "Helvetica-Bold"],
  ["HELVETICA_OBLIQUE", "Helvetica-Oblique"], ["HELVETICA_BOLD_OBLIQUE", "Helvetica-BoldOblique"],
  ["TIMES_ROMAN", "Times-Roman"], ["TIMES_BOLD", "Times-Bold"], ["TIMES_ITALIC", "Times-Italic"],
  ["TIMES_BOLD_ITALIC", "Times-BoldItalic"], ["SYMBOL", "Symbol"], ["ZAPF_DINGBATS", "ZapfDingbats"],
];
let rs = "// Generated by tools/gen-standard14.ts from Adobe's Core 14 AFM files (see NOTICE). Do not edit.\n";
rs += "// Each table maps a Unicode scalar to the glyph's advance width in 1/1000 em, sorted by scalar.\n\n";
for (const [id, file] of fonts) {
  const text = await Bun.file(`${dir}/${file}.afm`).text();
  const rows = new Map<number, number>();
  let missing = 0;
  for (const line of text.split(/\r?\n/)) {
    const m = /^C\s+-?\d+\s*;\s*WX\s+(\d+)\s*;\s*N\s+(\S+)\s*;/.exec(line);
    if (!m) continue;
    const unicode = unicodeFor(m[2]);
    if (unicode === undefined) { missing++; continue; }
    if (!rows.has(unicode)) rows.set(unicode, parseInt(m[1], 10));
  }
  const sorted = [...rows.entries()].sort((a, b) => a[0] - b[0]);
  const items = sorted.map(([u, w]) => `(0x${u.toString(16).padStart(4, "0")}, ${w})`);
  const lines: string[] = [];
  for (let i = 0; i < items.length; i += 8) lines.push(`    ${items.slice(i, i + 8).join(", ")},`);
  rs += `pub const ${id}: [(u16, u16); ${items.length}] = [\n${lines.join("\n")}\n];\n\n`;
  console.log(`${file}: ${items.length} glyphs, ${missing} names without Unicode`);
}
await Bun.write(out, rs);
