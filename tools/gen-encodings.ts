// gen-encodings.ts PDFIUM_ROOT OUT_RS
// Generates pdf-text/src/data/encodings.rs from PDFium's BSD-licensed encoding
// tables (see NOTICE). Code tables map a byte to a Unicode scalar; name tables
// map a byte to a glyph name. Pairing the two for every encoding yields the
// glyph-name lookup used for /Differences, so no separate glyph list is needed.
// Run with bun; the output is committed and regenerated only when PDFium changes.
const [root, out] = process.argv.slice(2);
if (!root || !out) {
  console.error("usage: bun gen-encodings.ts PDFIUM_ROOT OUT_RS");
  process.exit(1);
}
const fontSrc = await Bun.file(`${root}/core/fpdfapi/font/cpdf_fontencoding.cpp`).text();
const decodeSrc = await Bun.file(`${root}/core/fpdfapi/parser/fpdf_parser_decode.cpp`).text();

function body(src: string, name: string): string {
  const at = src.search(new RegExp(`\\b${name}\\b[^;]*?=`));
  if (at < 0) throw new Error(`table ${name} not found`);
  const open = src.indexOf("{", at);
  const close = src.indexOf("};", open);
  return src.slice(open, close);
}
function codes(src: string, name: string): number[] {
  const values = [...body(src, name).matchAll(/0x([0-9a-fA-F]{4})/g)].map((m) => parseInt(m[1], 16));
  if (values.length !== 256) throw new Error(`${name}: ${values.length} codes`);
  return values;
}
function names(src: string, name: string, size: number): string[] {
  const values = [...body(src, name).matchAll(/"([^"]*)"|nullptr/g)].map((m) => m[1] ?? "");
  if (values.length !== size) throw new Error(`${name}: ${values.length} names`);
  return values;
}

const tables: [string, number[], string[], number][] = [
  ["STANDARD", codes(fontSrc, "kStandardEncoding"), names(fontSrc, "kStandardEncodingNames", 224), 32],
  ["WIN_ANSI", codes(fontSrc, "kAdobeWinAnsiEncoding"), names(fontSrc, "kAdobeWinAnsiEncodingNames", 224), 32],
  ["MAC_ROMAN", codes(fontSrc, "kMacRomanEncoding"), names(fontSrc, "kMacRomanEncodingNames", 224), 32],
  ["MAC_EXPERT", codes(fontSrc, "kMacExpertEncoding"), names(fontSrc, "kMacExpertEncodingNames", 224), 32],
  ["SYMBOL", codes(fontSrc, "kAdobeSymbolEncoding"), names(fontSrc, "kAdobeSymbolEncodingNames", 224), 32],
  ["ZAPF_DINGBATS", codes(fontSrc, "kZapfEncoding"), names(fontSrc, "kZapfEncodingNames", 224), 32],
  ["PDF_DOC", codes(decodeSrc, "kPDFDocEncoding"), names(fontSrc, "kPDFDocEncodingNames", 232), 24],
];

const glyphs = new Map<string, number>();
for (const [, code, name, first] of tables) {
  name.forEach((glyph, i) => {
    const unicode = code[i + first];
    if (glyph && unicode && !glyphs.has(glyph)) glyphs.set(glyph, unicode);
  });
}
const sorted = [...glyphs.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const hex = (n: number) => `0x${n.toString(16).padStart(4, "0")}`;
const rows = (items: string[]) => {
  const lines: string[] = [];
  for (let i = 0; i < items.length; i += 8) lines.push(`    ${items.slice(i, i + 8).join(", ")},`);
  return lines.join("\n");
};
let rs = "// Generated by tools/gen-encodings.ts from PDFium tables (see NOTICE). Do not edit.\n\n";
for (const [id, code, name, first] of tables) {
  rs += `/// Byte to Unicode for ${id}; 0 means unmapped.\npub const ${id}: [u16; 256] = [\n${rows(code.map(hex))}\n];\n\n`;
  rs += `/// Byte to glyph name for ${id}, starting at byte ${first}; "" means unnamed.\n`;
  rs += `pub const ${id}_NAMES: [&str; ${name.length}] = [\n${rows(name.map((n) => JSON.stringify(n)))}\n];\n`;
  rs += `pub const ${id}_FIRST: usize = ${first};\n\n`;
}
rs += `/// Glyph name to Unicode, sorted by name for binary search.\npub const GLYPH_NAMES: [(&str, u16); ${sorted.length}] = [\n`;
rs += rows(sorted.map(([n, u]) => `(${JSON.stringify(n)}, ${hex(u)})`)) + "\n];\n";
await Bun.write(out, rs);
console.log(`wrote ${out}: ${tables.length} encodings, ${sorted.length} glyph names`);
